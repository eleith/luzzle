import type { Handle } from '@sveltejs/kit/hooks'
import { expect, test, vi } from 'vitest'
import { loadConfig } from '@luzzle/web.templates/config'
import { prepareConfiguredStyles, renderConfiguredStyles } from './configured-styles'

async function renderChunks(
	styles: string,
	chunks: string[],
	requestStyles = true
): Promise<string> {
	const response = await renderConfiguredStyles(
		{
			event: { locals: {} } as Parameters<Handle>[0]['event'],
			resolve: async (event, options) => {
				if (requestStyles) {
					event.locals.inlineConfiguredStyles()
					event.locals.inlineConfiguredStyles()
				}
				const rendered: string[] = []
				for (const [index, html] of chunks.entries()) {
					const transformed = await options?.transformPageChunk?.({
						html,
						done: index === chunks.length - 1
					})
					rendered.push(transformed ?? html)
				}
				return new Response(rendered.join(''))
			}
		},
		styles
	)
	return response.text()
}

const document =
	'<html><head><meta charset="utf-8">%luzzle.styles%<link rel="stylesheet" href="/fixed.css"></head><body></body></html>'

test('prepares only configured theme and editor CSS, not fixed stylesheets', async () => {
	const config = loadConfig()

	config.theme.light['color-primary'] = 'color-mix(in srgb, red 25%, blue)'
	config.theme.dark['color-primary'] = '#abcdef'
	config.theme.globals['space-4'] = 'calc(1rem + 2px)'
	config.theme.markdown.code = { light: 'rose-pine-dawn', dark: 'rose-pine' }

	const styles = await prepareConfiguredStyles(config)

	expect(styles).toContain('--color-primary: color-mix(in srgb, red 25%, blue);')
	expect(styles).toContain('--color-primary: #abcdef;')
	expect(styles).toContain('--space-4: calc(1rem + 2px);')
	expect(styles).toContain(":root[data-theme='dark']")
	expect(styles).toContain('@media (prefers-color-scheme: dark)')
	expect(styles).toContain('--editor-background: #faf4ed;')
	expect(styles).toContain('--editor-background: #191724;')

	for (const fixedRule of ['box-sizing:', '.button', 'pre.shiki', '.markdown {'])
		expect(styles).not.toContain(fixedRule)
})

test('layout requests insert one prepared block at the explicit token', async () => {
	const styles = await prepareConfiguredStyles(loadConfig())
	const html = await renderChunks(styles, [document])

	expect(html).toBe(document.replace('%luzzle.styles%', () => styles))
	expect(html.match(/<style data-luzzle-configured-styles>/g)).toHaveLength(1)
	expect(html.indexOf(styles)).toBeLessThan(html.indexOf('/fixed.css'))
	expect(html).not.toContain('%luzzle.styles%')
})

test('no layout request removes the token without adding CSS or leaking prior requests', async () => {
	const styles = await prepareConfiguredStyles(loadConfig())
	const unstyled = document.replace('%luzzle.styles%', '')

	expect(await renderChunks(styles, [document], false)).toBe(unstyled)
	expect(await renderChunks(styles, [document])).toContain('data-luzzle-configured-styles')
	expect(await renderChunks(styles, [document], false)).toBe(unstyled)
})

test('configured CSS is captured at preparation, not regenerated by requests', async () => {
	const config = loadConfig()

	config.theme.light['color-primary'] = '#123456'

	const original = await prepareConfiguredStyles(config)

	config.theme.light['color-primary'] = '#654321'

	const next = await prepareConfiguredStyles(config)

	for (let request = 0; request < 2; request++) {
		const html = await renderChunks(original, [document])
		expect(html).toContain('--color-primary: #123456;')
		expect(html).not.toContain('--color-primary: #654321;')
	}
	expect(await renderChunks(next, [document])).toContain('--color-primary: #654321;')
})

test.each([
	'"/fonts/custom.woff2"',
	'"https://fonts.example.test/custom.woff2?a=1&b=2"',
	'"fonts/custom.woff2"'
])('preserves the authored CSS font URL %s without rebasing or publishing files', async (url) => {
	const config = loadConfig()

	config.theme.globals['font-sans-url'] = url
	config.theme.globals['font-sans-name'] = '"Custom Sans"'
	config.theme.globals['font-sans-weight'] = '200 800'

	const styles = await prepareConfiguredStyles(config)

	expect(styles).toContain(`src: url(${url}) format('woff2');`)
	expect(styles).toContain('font-family: "Custom Sans";')
	expect(styles).toContain('font-weight: 200 800;')
})

test('CSS raw-text escaping preserves case, other less-than signs and dollar literals', async () => {
	const config = loadConfig()
	const content = '"$& $` $\' $$ \\</StYlE><script id=style-breakout>text</script>"'

	config.theme.markdown.sidenote['sidenote-callout-before-content'] = content
	config.theme.globals['font-sans-name'] = '"Custom < Sans"'

	const html = await renderChunks(await prepareConfiguredStyles(config), [document])

	expect(html.match(/<\/style/gi)).toHaveLength(1)
	expect(html).toContain(content.replace(/<\/style/gi, (tag) => tag.replace('/', '\\/')))
	expect(html).toContain('<\\/StYlE>')
	expect(html).toContain('font-family: "Custom < Sans";')
	expect(html.match(/<body>/g)).toHaveLength(1)
})

test('streaming handles the template token once and leaves body text alone', async () => {
	const styles = await prepareConfiguredStyles(loadConfig())
	const chunks = [
		'<html><head><meta charset="utf-8">',
		'%luzzle.styles%<link rel="stylesheet" href="/fixed.css">',
		'</head><body>',
		'<script>const marker = "%luzzle.styles%";</script>',
		'</body></html>'
	]
	for (let request = 0; request < 2; request++) {
		const html = await renderChunks(styles, chunks)
		expect(html.match(/<style data-luzzle-configured-styles>/g)).toHaveLength(1)
		expect(html).toContain('<script>const marker = "%luzzle.styles%";</script>')
	}
})

test('leaves non-HTML bodies and framework cache/CSP headers unchanged', async () => {
	const styles = await prepareConfiguredStyles(loadConfig())
	const event = { locals: {} } as Parameters<Handle>[0]['event']
	const response = new Response('{"ok":true}', {
		headers: {
			'content-type': 'application/json',
			'cache-control': 'private, no-store',
			'content-security-policy': "script-src 'self' 'nonce-framework'"
		}
	})

	const resolve = vi.fn<Parameters<Handle>[0]['resolve']>().mockResolvedValue(response)

	expect(await renderConfiguredStyles({ event, resolve }, styles)).toBe(response)
	expect(typeof event.locals.inlineConfiguredStyles).toBe('function')
	expect(await response.text()).toBe('{"ok":true}')
	expect(response.headers.get('cache-control')).toBe('private, no-store')
	expect(response.headers.get('content-security-policy')).toBe(
		"script-src 'self' 'nonce-framework'"
	)
})
