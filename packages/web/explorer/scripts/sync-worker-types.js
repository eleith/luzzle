#!/usr/bin/env node
// Copies pure-type files from packages/web/worker/src/api/ into
// packages/web/explorer/src/lib/worker-api/.
//
// The destination directory is gitignored. This script is the single source
// of truth for keeping the explorer's view of worker Job payload/result types
// in sync with the worker package. It is NOT auto-hooked into prebuild or
// postinstall — a fresh clone that skips this step fails loudly at typecheck,
// which is the intended signal.

import { readFileSync, writeFileSync, readdirSync, mkdirSync, rmSync, statSync } from 'node:fs'
import { dirname, resolve, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url))
const SOURCE = resolve(SCRIPT_DIR, '../../worker/src/api')
const DEST = resolve(SCRIPT_DIR, '../src/lib/worker-api')
const HEADER =
	'// DO NOT EDIT — generated by `npm run sync-worker-types`.\n' +
	'// Source: packages/web/worker/src/api/\n\n'

function copyTree(src, dst) {
	mkdirSync(dst, { recursive: true })
	let count = 0
	for (const entry of readdirSync(src)) {
		const srcPath = join(src, entry)
		const dstPath = join(dst, entry)
		const s = statSync(srcPath)
		if (s.isDirectory()) {
			count += copyTree(srcPath, dstPath)
		} else if (entry.endsWith('.ts')) {
			const content = readFileSync(srcPath, 'utf8')
			writeFileSync(dstPath, HEADER + content)
			count++
		}
	}
	return count
}

try {
	statSync(SOURCE)
} catch {
	console.error(`sync-worker-types: source not found: ${SOURCE}`)
	process.exit(1)
}

rmSync(DEST, { recursive: true, force: true })
const written = copyTree(SOURCE, DEST)
console.log(`sync-worker-types: copied ${written} file(s) into src/lib/worker-api/`)
